const normalize = (value: string) => value.toLowerCase().replace(/[’ʼ']/g, "'");

const matchesKeyword = (text: string, keyword: string) => {
  const stem = normalize(keyword);
  const escaped = stem.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const end =
    stem.length <= 3 && !stem.includes(' ') ? '(?:$|[^\\p{L}\\p{N}])' : '';
  return new RegExp(`(?:^|[^\\p{L}\\p{N}])${escaped}${end}`, 'iu').test(text);
};

export const shoppingAisleOf = (
  nameEn: string,
  nameUk: string,
): ShoppingAisle => {
  const text = normalize(`${nameEn} ${nameUk}`);
  for (const rule of RULES) {
    if (rule.keywords.some((keyword) => matchesKeyword(text, keyword))) {
      return rule.id;
    }
  }
  return 'other';
};
